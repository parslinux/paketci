"""Unit tests for audit and export commands."""

from typer.testing import CliRunner

from paketci.cli.app import app
from paketci.core import audit, export

runner = CliRunner()


def test_export_requirements(tmp_path):
    content = export.export_requirements(include_hashes=False)
    assert "Generated by paketci" in content or "paketci.lock" in content
    assert "httpx==" in content
    assert "rich==" in content


def test_export_cli_stdout():
    result = runner.invoke(app, ["export", "--no-hashes"])
    assert result.exit_code == 0
    assert "httpx==" in result.output


def test_export_cli_file(tmp_path):
    out_file = tmp_path / "reqs.txt"
    result = runner.invoke(app, ["export", "-o", str(out_file), "--no-hashes"])
    assert result.exit_code == 0
    assert out_file.is_file()
    assert "httpx==" in out_file.read_text()


def test_audit_clean_project():
    # Mevcut projemizin kilitli paketleri temizdir
    res = audit.audit()
    assert res.packages_scanned > 0
    assert not res.has_vulnerabilities
